%{
Date Created: 2/22/2025
Description:
This script generates a series of group-level plots from precomputed 
LFP, spectrogram, and PSD results.

It assumes that the following variables have already been created in the
workspace (e.g., via `aggBehavior.mlx` and related preprocessing 
scripts):

    Core behavioral/metadata:
        - behav_table: master table of sessions/trials.
        - pl_full_cri, pl_zero_cri: logical masks for passive listening
        full-volume vs zero-volume trials.
        - gonogo_full_cri, gonogo_zero_cri: masks for go/no-go full vs
        zero trials.
        - all_full_cri, all_zero_cri: masks combining advanced sessions 
        and passive listening across tasks.
        - all_full_data, all_zero_data: preloaded LFP trial data 
        structures for all_full and all_zero conditions (used by PSD 
        code).
        - time_segments: cell array of index ranges used for PSD time
        windows (baseline, early, late).

    Spectrogram (time–frequency) results:
        - fft_all_conds: struct containing baseline-normalized 
        spectrogram arrays for each condition and channel.
        - fft_time_vec: time vector for spectrograms (in seconds).
        - fft_freqs: frequency vector for spectrograms (in Hz).
        - an_names_all_conds: matching animal IDs per condition/channel.

    PSD results:
        - pxx_result: struct of PSD estimates per condition, channel, 
        and time segment (as generated by runPSD).
        - pxx_freq: frequency vector for PSD (in Hz).

    Permutation-based significance results:
        - Cluster-based permutation outputs for spectrograms and PSDs 
        have been saved to disk under `save_root` and can be accessed 
        by:
            getStatResults      (for spectrograms)
            getStatResults_psd  (for PSD segments)

The script performs the following steps:
    1. Plots group-averaged spectrograms for all_full and all_zero, and
    their difference (all_full - all_zero).
    2. Uses permutation-based cluster statistics to generate difference
    spectrograms with significance masks applied.
    3. Uses permutation results to identify significant PSD frequencies 
    and saves them to disk.
    4. Plots group-level PSD curves (baseline-normalized) for all_full 
    vs all_zero, and optionally for lick vs no-lick across intensity
    quantiles.
%}

