%% Functions: group difference spectrograms (cond1 - cond2)
function plotGroupDifferenceSpectrogram(data_all_conds,cond1_name,cond2_name,animals_all_conds,time_vec,freqs,save_dir,y_limits,color_limits)
        
        % Extract data and animal names for the two conditions.
        cond1_data = data_all_conds.(cond1_name); 
        cond2_data = data_all_conds.(cond2_name);

        cond1_animals = animals_all_conds.(cond1_name); 
        cond2_animals = animals_all_conds.(cond2_name);

        new_ch_locations = fieldnames(cond1_data) ;

        % Loop over channels and compute the animal-wise difference between
        % conditions, then average across animals to obtain a group-level
        % difference spectrogram.
        for ic = 1:length(new_ch_locations)
            
            this_ch = new_ch_locations{ic}; 

            this_ch_cond1_data = cond1_data.(this_ch) ; 
            this_ch_cond2_data = cond2_data.(this_ch) ; 
        
            this_ch_cond1_animals = cond1_animals.(this_ch) ;
            this_ch_cond2_animals = cond2_animals.(this_ch) ;
    
            % Ensure we only compare animals present in both conditions.
            if length(this_ch_cond1_animals) ~= length(this_ch_cond2_animals)
               common_animals = intersect(this_ch_cond1_animals,this_ch_cond2_animals) ; 
               
               this_ch_cond1_animals = this_ch_cond1_animals(ismember(this_ch_cond1_animals,common_animals));
            end 

            if isempty(this_ch_cond1_animals)
                continue 
            end 

            % Compute cond1 − cond2 spectrogram per animal.
            for in = 1:length(this_ch_cond1_animals)
    
                this_an = this_ch_cond1_animals{in};
                this_an_cond1_data = this_ch_cond1_data(:,:,in);
                this_an_cond2_data = this_ch_cond2_data(:,:,in);

                all_an_minus_data(:,:,in) = this_an_cond1_data - this_an_cond2_data ; 
            
            end 
            
            try
            group_minus_data = nanmean(all_an_minus_data,3) ; 
            catch   
                keyboard
            end

            % Plot the group-level difference spectrogram.
            figure; 

            colormap jet 
            imagesc(time_vec,freqs,squeeze(group_minus_data))
            ax = gca;
            ax.YDir= 'normal';
            a = colorbar ; 

            if ~isempty(color_limits)
                clim(color_limits)
            end 

            ylabel('Freqeuncy (Hz)') 
            xlabel('Time (sec)') 
            title(strcat(this_ch,'_',cond1_name,'_minus_',cond2_name),'Interpreter','none')
            xline([0 0],'k') 
    
            if ~isempty(y_limits)
                ylim(y_limits)
            end 
            xlim([-1 1])
            h = colorbar; 
            title(h,'Log(mV^2)')
            legend(['n = ' int2str(size(all_an_minus_data,3))])

        end 
        

end

