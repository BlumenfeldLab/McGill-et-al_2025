%% Functions: group PSD plotting and baseline normalization
function [out_result,bl_result] = plotPSD(pxx_result,pxx_freq,cond_pairs,seg_names,colors,x_limits,y_limits,description)
    % Plot group-level PSD curves for condition pairs across time segments.
    % Segment 1 is treated as baseline, and later segments are normalized
    % by subtracting the log power of the baseline PSD.
    %
    % Outputs:
    %   out_result.(cond).(channel){seg} : baseline-normalized PSD for each
    %       non-baseline segment (one entry per time segment).
    %   bl_result.(cond).(channel)       : baseline PSD (in dB).

    all_channels = fieldnames(pxx_result.(cond_pairs{1}{1}));
    for ic = 1:length(all_channels)
         curr_ch = all_channels{ic} ; 

             for ipair = 1:length(cond_pairs)
             curr_pair = cond_pairs{ipair}; 
             
            f=figure;
             for icond = 1:length(curr_pair)
                 curr_cond = curr_pair{icond} ; 
    
                subplot(2,1,icond)
                hold on 

                % Segment 1 is baseline; subtract its log power from
                % later segments.
                baseline_seg = pxx_result.(curr_cond).(curr_ch){1}; 
                for iseg = 2:length(seg_names)
       
                    curr_data = pxx_result.(curr_cond).(curr_ch){iseg} ; 
                    curr_data = pow2db(curr_data) - pow2db(baseline_seg); 
                    
                    getse = @(x) std(x,0,2)/sqrt(size(x,2));

                    shadedErrorBar(pxx_freq,nanmean(curr_data,2),getse(curr_data),...
                        'lineProps',colors{iseg-1})

                    out_result.(curr_cond).(curr_ch){iseg-1} = curr_data ;
                    
                end 

                bl_result.(curr_cond).(curr_ch) = pow2db(baseline_seg); 
                
                legend(seg_names(2:3))
                xlim(x_limits)
                if ~isempty(y_limits)
                ylim(y_limits)
                end 
  
                title([curr_ch ' ' curr_cond ' ' ['n=' int2str(size(curr_data,2))] ' ' description],'Interpreter','none')
            
                ylabel('PSD (db/Hz)')
                xlabel('Frequency (Hz)')
                fontsize(f, 18, "points")

                yline([0 0],'LineStyle','--','Color','k' )
             end 
    
             
             end 
        end
         
    
end

%% Functions: cluster-size filtering for permutation tests
function [good_pos_ids,good_neg_ids] = checkClusterSize(input_data)
    % Filter positive and negative clusters based on both p-value (< 0.05)
    % and relative size (greater than a cutoff fraction of the total
    % time–frequency grid).
    cutoff = 0.01;

    pos_clust = find(input_data.clust_info.pos_clust_pval < 0.05);
    
    good_pos_ids = []; 
    for iid = 1:length(pos_clust)
        curr_id = pos_clust(iid); 

        curr_id_size = sum(input_data.clust_info.pos_clust_ids==curr_id,'all'); 

        if curr_id_size > numel(input_data.clust_info.pos_clust_ids)*cutoff
            good_pos_ids = [good_pos_ids curr_id]; 
        end
      
    end 

    neg_clust = find(input_data.clust_info.neg_clust_pval < 0.05);
    
    good_neg_ids = []; 
    for iid = 1:length(neg_clust)
        curr_id = neg_clust(iid); 

        curr_id_size = sum(input_data.clust_info.neg_clust_ids==curr_id,'all'); 

        if curr_id_size > numel(input_data.clust_info.neg_clust_ids)*cutoff
            good_neg_ids = [good_neg_ids curr_id]; 
        end
      
    end 
    
end

%% Functions: recover significant freq bands for PSD from permutation results
function all_seg_sig = getStatResults_psd(segs,fft_time,fft_freqs,stat_dir,curr_ch_name,curr_cond_name) 

    num_permutation = 5000  ; 

    % Load permutation-based cluster statistics for the given channel and
    % condition contrast.
    input_data = load(fullfile(stat_dir,curr_cond_name,[ curr_ch_name '_permutation_stat_cluster_sumt_rand_005_',num2str(num_permutation),'_perm_' curr_cond_name '.mat']));

    curr_data = squeeze(nanmean(input_data.curr_ch_data,3));
    
    data_matrix = zeros(size(curr_data));

    % Identify cluster IDs that pass p-value and size thresholds.
    [pos_clust,neg_clust] = checkClusterSize(input_data); 
    
    % Fill positive clusters into data_matrix.
    for clust = 1:length(pos_clust)
        for time = 1:size(data_matrix,2)
            [sig_grid_voxels, col] = find(input_data.clust_info.pos_clust_ids(:,time) == pos_clust(clust));
            data_matrix(sig_grid_voxels,time) = curr_data(sig_grid_voxels,time);

        end
    end
    
    % Fill negative clusters into data_matrix.
    for clust = 1:length(neg_clust)
        for time = 1:size(data_matrix,2)
            [sig_grid_voxels, col] = find(input_data.clust_info.neg_clust_ids(:,time) == neg_clust(clust));
            data_matrix(sig_grid_voxels,time) = curr_data(sig_grid_voxels,time);
        end
    end

    % For each requested time segment, identify frequencies that show any
    % significant deviation and return their corresponding frequency 
    % values.
    for iseg = 1:length(segs)
        curr_seg_time_pts = segs{iseg} -1375; 

        start_time = curr_seg_time_pts(1) ./ 1000; 
        end_time = curr_seg_time_pts(end) ./ 1000; 

        sel_time_pts = fft_time < end_time & fft_time > start_time ; 


        curr_sig_freq = find(any(data_matrix(:,sel_time_pts) ~= 0,2)) ;

        
        all_seg_sig{iseg} = fft_freqs(curr_sig_freq); 
    end 
 
end

%% Functions: reconstruct significant difference maps from permutation results
