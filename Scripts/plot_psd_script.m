            % map for this channel and condition contrast.
            curr_data_w_sig = getStatResults(save_root,curr_ch,curr_data_type) ;

            % Plot difference spectrogram with significance applied.
            plotWithSigGroupDifferenceSpectrogram(curr_data_w_sig,fft_time_vec,...
                fft_freqs,curr_ch,curr_data_type,[0 100],[-0.5 0.5])

        end 
end 

