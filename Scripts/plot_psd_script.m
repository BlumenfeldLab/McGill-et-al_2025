    curr_data = squeeze(nanmean(input_data.curr_ch_data,3));
    
    data_matrix = zeros(size(curr_data));

    % Identify cluster IDs that pass p-value and size thresholds.
    [pos_clust,neg_clust] = checkClusterSize(input_data); 
    
    % Fill positive clusters into data_matrix.
    for clust = 1:length(pos_clust)
        for time = 1:size(data_matrix,2)
            [sig_grid_voxels, col] = find(input_data.clust_info.pos_clust_ids(:,time) == pos_clust(clust));
            data_matrix(sig_grid_voxels,time) = curr_data(sig_grid_voxels,time);
        end
    end
    
    % Fill negative clusters into data_matrix.
