%% Plot group difference spectrograms (all_full - all_zero)
% Plot the group-average difference spectrogram (all_full minus all_zero)
% across animals and channels, using `plotGroupDifferenceSpectrogram`. This
% highlights condition differences in the time–frequency domain prior to
